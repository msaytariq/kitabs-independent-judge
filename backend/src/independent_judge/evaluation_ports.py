"""Evaluation adapters depend on these small application-facing contracts."""
from decimal import Decimal
from typing import Protocol
from independent_judge.domain.evaluation import Prompt,JudgeConfig,LlmResult


class JudgePort(Protocol):
    def complete(self,prompt: Prompt,config: JudgeConfig) -> LlmResult: ...


class BudgetPort(Protocol):
    def reserve(self,run_id: str,call_id: str,estimate: Decimal): ...
    def settle(self,run_id: str,call_id: str,actual: Decimal): ...
    def summary(self,run_id: str | None = None) -> dict: ...


class RunPort(Protocol):
    def begin(self,run_id: str,request: dict): ...
    def receipt(self,run_id: str,call_id: str,snapshot: dict): ...
    def finish(self,run_id: str,report: dict): ...
    def get(self,run_id: str) -> dict | None: ...
