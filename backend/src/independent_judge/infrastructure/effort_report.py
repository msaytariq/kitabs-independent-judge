"""Forecast explanation for the portable report; no editable time fields."""
from html import escape


def effort_html(effort: dict) -> str:
    value = effort['reduction_percent']
    heading = 'Недостаточно данных для прогноза' if value is None else (
        f'Прогноз сокращения трудозатрат на исправления B относительно A: {value:g}%')
    rows = ''.join(f'<p>{side.upper()}: {s["edits"] if s["edits"] is not None else "не оценено"} '
                   f'кандидатов на исправление; исключено спорных или непривязанных: {s["excluded"]}.</p>'
                   for side, s in effort['sides'].items())
    return f'''<section><h2>{escape(heading)}</h2>{rows}
    <p>Прогноз по находкам модели, не измерение времени. Веса сложности условные и не откалиброваны:
    критические — 5, терминология — 3, аппарат — 4, стиль — 1. Одинаковы для A и B.</p>
    <p>Чувствительность к весам: {escape(str(effort['sensitivity_percent']))}.
    Это диапазон сценариев, не доверительный интервал.</p>
    <p>Формула: (1 − работа B / работа A) × 100%. При нулевой базе процент не определяется.
    100% означает отсутствие включённых находок в B, а не отсутствие работы редактора.
    Чтение, проверка правильных мест и предыдущий человеческий труд не оценены.
    Проверенные готовые элементы аппарата не требуют создания заново; само число сносок не даёт бонус.</p></section>'''
