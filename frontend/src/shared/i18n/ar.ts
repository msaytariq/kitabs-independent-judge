// Texts with values: the English pattern and its Arabic form; {0}, {1} keep their order.
export const AR_PATTERNS: [RegExp, string][] = [
  [/^wrong: (\d+)$/, 'خاطئة: {0}'],
  [/^done: (\d+)$/, 'منجزة: {0}'],
  [/^broken sentences: (\d+)$/, 'جمل مقطوعة: {0}'],
  [/^Fragment (\d+) of (\d+)$/, 'الجزء {0} من {1}'],
  [/^breaks: (\d+) of (\d+)$/, 'انقطاعات: {0} من {1}'],
  [/^remaining: (\d+)$/, 'متبقية: {0}'],
  [/^(\d+) of the demonstration launches remain\.$/, 'التشغيلات المتبقية للعرض: {0}.'],
  [/^(\S+) of (\S+)$/, '{0} من {1}'],
  [/^(\S+) has no errors with quotations\.$/, 'لا أخطاء مع اقتباسات في {0}.'],
  [/^A needs less editing time: (\d+) against (\d+) minutes$/, 'تحتاج A إلى تحرير أقل: {0} دقيقة مقابل {1}'],
  [/^Assumption: (\d+) minutes for one edit by an editor; 5 seconds to accept one edit that Kitabs has already applied\.$/,
    'افتراض: {0} دقائق لكل تعديل يجريه المحرِّر؛ و5 ثوانٍ لقبول تعديل طبَّقه Kitabs مسبقًا.'],
  [/^B saves (-?\d+)% of the editing time$/, 'توفِّر B نسبة {0}٪ من زمن التحرير'],
  [/^Different winners: (.+) and (.+)$/, 'الفائزان مختلفان: {0} و{1}'],
  [/^Hadith: (\d+) of (\d+) found$/, 'الأحاديث: عُثر على {0} من {1}'],
  [/^Quran verses: (\d+) of (\d+) found$/, 'آيات القرآن: عُثر على {0} من {1}'],
  [/^Same winner: (.+)$/, 'الفائز نفسه: {0}'],
  [/^Translation (\S+)$/, 'الترجمة {0}'],
  [/^Printed in the edition: "(.*)" — in the Quran: (.+)$/, 'المطبوع في الطبعة: «{0}» — في القرآن: {1}'],
  [/^level (\d+) of 5$/, 'المستوى {0} من 5'],
];

export function arabic(en: string): string {
  if (en in AR) return AR[en];
  for (const [pattern, form] of AR_PATTERNS) {
    const match = pattern.exec(en);
    if (match) return form.replace(/\{(\d)\}/g, (_, i) => AR[match[Number(i) + 1]] ?? match[Number(i) + 1]);
  }
  return en;
}
